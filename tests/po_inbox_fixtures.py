"""The mod's contract fixtures: the raw `squad-inbox list --json` output over scripted homes.

Regenerate with `python3 tests/po_inbox_fixtures.py` (writes hooks/po-inbox/fixtures/contract-*.ts). Never edit those by hand:
tests/test_po_inbox_contract.py compares them with what this script produces.
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLI = str(ROOT / "bin" / "squad-inbox")
OUT = ROOT / "hooks" / "po-inbox" / "fixtures"
NOW = "2026-10-15T12:00:00Z"
HEAD = ("# Escalations\n\n| # | Date | Question | Options | Manager's recommendation | Blocks | Answer |\n"
        "|---|---|---|---|---|---|---|\n")
MIXED_ROWS = ("| 3 | 2026-10-15 | Merge the inbox branch?<br>body line | (a) yes; (b) no | (a) | PI-07 | |\n"
              "| 2 | 2026-10-15 | Which port?<br>body line | | | | |\n")
AGENT_ENV = ("SQUAD_DIR", "SCOPE_DIR", "GOAL_DIR", "SQUAD_NAME", "SQUAD_ROLE", "SQUAD_SCOPE")


def cli(home, now, *args, stdin=""):
    env = {k: v for k, v in os.environ.items() if k not in AGENT_ENV}
    env.update(SQUAD_ROLE="manager", SQUAD_INBOX_NOW=now, PYTHONDONTWRITEBYTECODE="1")
    done = subprocess.run([sys.executable, CLI, "--home", str(home), *args], input=stdin, text=True,
                          capture_output=True, env=env)
    assert done.returncode == 0, (args, done.stderr)
    return done.stdout


def mixed():
    with tempfile.TemporaryDirectory() as home:
        (Path(home) / "escalations.md").write_text(HEAD + MIXED_ROWS)
        cli(home, "2026-10-15T09:00:00Z", "add", "--kind", "read", "--title", "Spec digest", stdin="body line")
        cli(home, "2026-10-13T09:00:00Z", "add", "--kind", "read", "--title", "Old note", stdin="body line")
        cli(home, "2026-10-14T10:00:00Z", "read", "R2")
        cli(home, "2026-10-15T11:00:00Z", "answer", "E2", "--text", "8080", "--source", "pane")
        return cli(home, NOW, "list", "--json").replace(home, "/tmp/home")


def empty():
    with tempfile.TemporaryDirectory() as home:
        return cli(home, NOW, "list", "--json").replace(home, "/tmp/home")


def full_home():
    return cli(ROOT / "tests" / "fixtures" / "inbox" / "home", NOW, "list", "--json", "--no-write").replace(
        str(ROOT / "tests" / "fixtures" / "inbox" / "home"), "/tmp/home")


FIXTURES = {"contract-mixed": mixed, "contract-empty": empty, "contract-home": full_home}


def ts_text(name, text):
    import json
    return ("// Raw output of `squad-inbox list --json` (%s). Generated by tests/po_inbox_fixtures.py; do not edit.\n"
            "export default %s\n" % (name, json.dumps(text)))


def main():
    for name, build in FIXTURES.items():
        (OUT / (name + ".ts")).write_text(ts_text(name, build()))
    names = sorted(FIXTURES)
    lines = ["// Every contract fixture; the tests run on all of them. Generated by tests/po_inbox_fixtures.py."]
    lines += ["import %s from './%s'" % (n.replace("-", "_"), n) for n in names]
    lines += ["", "export const FIXTURES: Record<string, string> = {"]
    lines += ["  '%s': %s," % (n, n.replace("-", "_")) for n in names] + ["}", ""]
    (OUT / "index.ts").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
